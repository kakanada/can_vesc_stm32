/*  Приём и HAL callback-и - теперь дело can_manager, не motor_vesc         */
/* ------------------------------------------------------------------------ */
/*
 * До миграции на can_manager у motor_vesc были СВОИ обработчики
 * (VESC_CAN_RxFifo0_Handler/TxComplete_Handler/ErrorStatus_Handler),
 * которые вы вызывали из своих HAL callback-ов, и своя точка расширения
 * VESC_CAN_OnForeignFrame() для чужих кадров/устройств на той же шине.
 * Все они удалены - приём кадров, обработка Bus-Off/переполнения Rx FIFO0
 * и низкоуровневая отправка (включая примитив "сырой кадр в обход очереди",
 * был VESC_CAN_SendRawFrame) теперь целиком на can_manager:
 *
 *   - вызывайте `CANMGR_RxFifo_Handler`/`CANMGR_TxComplete_Handler`/
 *     `CANMGR_ErrorStatus_Handler` (см. can_manager.h) из своих HAL
 *     callback-ов - см. шпаргалку по обоим бэкендам там же;
 *   - "чужие" кадры/устройства на той же шине - отдельный, свой
 *     `CANMGR_RegisterFilter()` (или отдельный модуль, зарегистрировавший
 *     свой фильтр - именно так теперь получает свои кадры vesc_bridge.h,
 *     без какой-либо связи с motor_vesc.c);
 *   - диагностику Bus-Off/переполнения Rx FIFO0 читайте напрямую:
 *     `CANMGR_GetBusOffCount(bus)`/`CANMGR_GetRxOverflowCount(bus)`.
 *
 * Внутри motor_vesc.c приём теперь работает через собственный callback,
 * зарегистрированный в can_manager при VESC_CAN_Init()/RegisterCustomStatus()/
 * SetLocalId() (см. .c) - он статический (не публичный API), вызывающему
 * коду про него знать не нужно, он просто находит нужный VESC_Handle_t по
 * (bus, vesc_id) внутри модуля и передаёт кадр в уже существующий
 * vesc_decode_status() - её собственная логика (телеметрия, губернаторы,
 * память положения, реестр кастомных статусов) не изменилась ни на строку.
 */

/* ------------------------------------------------------------------------ */
/*  Колбэк приёма телеметрии (любой статусный пакет)                        */
/* ------------------------------------------------------------------------ */
/*
 * Для СВОИХ, уже опознанных статусных кадров КОНКРЕТНОЙ вески. Актуальные
 * данные всегда доступны и без колбэка - через h->telemetry в любом месте
 * кода в любой момент. Колбэк нужен, когда реагировать на приём телеметрии
 * требуется СРАЗУ, в момент приёма кадра, а не при следующем удобном опросе
 * (например, чтобы тут же прокинуть значение в общий пакет телеметрии
 * системы, пересчитать что-то зависящее от него, либо переслать данные ещё
 * куда-то).
 */

/**
 * @brief  Задаёт функцию-обработчик, которая будет вызвана при получении
 *         КАЖДОГО распознанного статусного пакета телеметрии этой вески
 *         (VESC_CAN_PACKET_STATUS, STATUS_2 .. STATUS_7 - см.
 *         VESC_TelemetryCallback_t). Передайте NULL, чтобы отключить ранее
 *         заданный обработчик.
 *
 * @warning См. предупреждение у типа VESC_TelemetryCallback_t выше -
 *          обработчик вызывается ИЗ ПРЕРЫВАНИЯ, должен быть быстрым.
 *
 * @param  h         хэндл вески
 * @param  callback  функция-обработчик (см. VESC_TelemetryCallback_t),
 *                    либо NULL чтобы отключить
 * @retval HAL_OK; HAL_ERROR если h == NULL
 */
HAL_StatusTypeDef VESC_CAN_SetTelemetryCallback(VESC_Handle_t *h, VESC_TelemetryCallback_t callback);

/* ------------------------------------------------------------------------ */
/*  Кастомный датчик, подключённый к веске (byte[1] статуса №7)             */
/* ------------------------------------------------------------------------ */
/*
 * Актуальное значение всегда доступно в h->telemetry.custom_sensor_state -
 * читать его можно и без колбэка, опрашивая в своём коде когда удобно.
 * Колбэк ниже - для случаев, когда реагировать нужно СРАЗУ по приходу
 * кадра, не дожидаясь следующего цикла опроса вашего кода.
 */

/**
 * @brief  Задаёт функцию-обработчик, которая будет вызвана при получении
 *         статуса кастомного датчика (VESC_CAN_PACKET_STATUS_7) со
 *         значением "pin-set" либо "pin-reset" (т.е. НЕ "none"/0x00).
 *         Вызывается КАЖДЫЙ РАЗ при получении такого кадра (не только при
 *         изменении значения относительно предыдущего кадра). Передайте
 *         NULL, чтобы отключить ранее заданный обработчик.
 *
 * @warning См. предупреждение у типа VESC_CustomSensorCallback_t выше -
 *          обработчик вызывается ИЗ ПРЕРЫВАНИЯ, должен быть быстрым.
 *
 * @param  h         хэндл вески
 * @param  callback  функция-обработчик (см. VESC_CustomSensorCallback_t),
 *                    либо NULL чтобы отключить
 * @retval HAL_OK; HAL_ERROR если h == NULL
 */
HAL_StatusTypeDef VESC_CAN_SetCustomSensorCallback(VESC_Handle_t *h, VESC_CustomSensorCallback_t callback);

/* ------------------------------------------------------------------------ */
/*  Имитация весок для отладки без физической CAN-шины                      */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Помечает веску как имитируемую ("фейковую") или реальную.
 *         По умолчанию (сразу после VESC_CAN_Init) все вески считаются
 *         реальными. Вызов вне зависимости от VESC_CAN_SIM_ENABLE
 *         компилируется - при VESC_CAN_SIM_ENABLE == 0 это пустая заглушка.
 *
 * @param  h             хэндл вески
 * @param  is_simulated  0 - реальная веска (по умолчанию), 1 - имитируемая
 */
void VESC_CAN_SetSimulated(VESC_Handle_t *h, uint8_t is_simulated);

/**
 * @brief  Один шаг имитации: для КАЖДОЙ вески на ЛЮБОЙ шине, помеченной как
 *         имитируемая (VESC_CAN_SetSimulated), генерирует правдоподобные
 *         данные "двигателя без нагрузки" (разгон/торможение к последней
 *         отправленной через VESC_CAN_SendSpeed скорости, малый ток,
 *         накопительные Ah/Wh, температура и т.д.) и обновляет её телеметрию
 *         так, как будто одновременно пришли все 7 статусных пакетов. Дельта
 *         времени считается автоматически по HAL_GetTick() между вызовами -
 *         вызывайте эту функцию периодически (например из обработчика
 *         прерывания таймера), интервал вызова может быть произвольным.
 *
 *         При VESC_CAN_SIM_ENABLE == 0 - пустая заглушка, вызов безопасен и
 *         ничего не делает (не нужно убирать вызовы из остального кода).
 */
void VESC_CAN_SimulateTick(void);

