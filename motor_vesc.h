/* ------------------------------------------------------------------------ */
/*  Конфигурация модуля (define-ы, меняются до включения заголовка)         */
/* ------------------------------------------------------------------------ */

/** Максимальное число одновременно зарегистрированных весок СУММАРНО по
 *  всем шинам вместе взятым (не на одну шину). */
#ifndef VESC_CAN_MAX_DEVICES
#define VESC_CAN_MAX_DEVICES            24U
#endif

/** Максимальное число независимых CAN-шин, на которых модуль умеет работать
 *  одновременно (например CAN1+CAN2, либо FDCAN1+FDCAN2). */
#ifndef VESC_CAN_MAX_BUSES
#define VESC_CAN_MAX_BUSES               2U
#endif

/** Сколько РАЗНЫХ команд одновременно может "ждать своей очереди" для одной
 *  вески, если аппаратный буфер периферии переполнен (см. VESC_CAN_SendXxx).
 *  4 с большим запасом хватает для реальных сценариев (обычно ждёт 0-1). */
#ifndef VESC_CAN_MAX_PENDING_PER_VESC
#define VESC_CAN_MAX_PENDING_PER_VESC    4U
#endif

/** Сколько РАЗНЫХ кастомных cmd_id (см. VESC_CAN_RegisterCustomStatus) можно
 *  зарегистрировать в can_manager СУММАРНО по всем вескам ОДНОЙ шины -
 *  отдельно от VESC_CAN_MAX_CUSTOM_STATUSES (тот лимит - на одну веску, этот
 *  - на уникальные коды на шине, т.к. can_manager фильтр по cmd_id общий для
 *  всех весок этой шины и регистрируется только один раз на код, см.
 *  motor_vesc.c). Небольшое значение с запасом - реалистично на шине
 *  одновременно используется всего несколько различных кастомных cmd_id. */
#ifndef VESC_CAN_MAX_CUSTOM_FILTERS_PER_BUS
#define VESC_CAN_MAX_CUSTOM_FILTERS_PER_BUS   8U
#endif

/** Сколько РАЗНЫХ значений "нашего локального ID" (см. VESC_CAN_SetLocalId)
 *  можно зарегистрировать под PONG-фильтр can_manager суммарно на ОДНУ шину.
 *  В норме используется одно значение на всё время работы программы - запас
 *  только на случай, если вызывающий код меняет local_id на лету несколько
 *  раз (can_manager не даёт снять регистрацию предыдущего значения - см.
 *  честное объяснение в motor_vesc.c у vesc_register_pong_filter). */
#ifndef VESC_CAN_MAX_LOCAL_IDS_PER_BUS
#define VESC_CAN_MAX_LOCAL_IDS_PER_BUS   4U
#endif

/**
 * Включает/выключает весь код программной имитации весок (для отладки без
 * физической CAN-шины). При VESC_CAN_SIM_ENABLE == 0 функции имитации
 * остаются объявленными и вызываемыми (компилируются в пустые заглушки),
 * поэтому вызовы из остального кода можно не вырезать - достаточно
 * поменять этот define.
 */
#ifndef VESC_CAN_SIM_ENABLE
#define VESC_CAN_SIM_ENABLE              1
#endif

/** Сколько РАЗНЫХ кастомных статусов (сверх штатного STATUS_7) может быть
 *  одновременно зарегистрировано на ОДНУ веску через
 *  VESC_CAN_RegisterCustomStatus() - см. секцию "Произвольные кастомные
 *  статусы" ниже. */
#ifndef VESC_CAN_MAX_CUSTOM_STATUSES
#define VESC_CAN_MAX_CUSTOM_STATUSES     4U
#endif

/** Таймаут (мс) для VESC_CAN_GetExistStatus() - если после
 *  VESC_CAN_RequestExists() PONG не пришёл за это время, статус считается
 *  VESC_EXIST_TIMEOUT (веска не ответила за отведённое время). Один и тот
 *  же таймаут для всех весок сразу - если нужен другой на конкретной
 *  веске, вызывайте VESC_CAN_RequestExists() повторно с другим ожиданием
 *  на своей стороне (сам факт истечения таймаута ничего не портит). */
#ifndef VESC_CAN_EXIST_TIMEOUT_MS
#define VESC_CAN_EXIST_TIMEOUT_MS        200U
#endif

/* ------------------------------------------------------------------------ */
/*  Коды команд/статусов протокола VESC CAN (см. datatypes.h проекта bldc)  */
/* ------------------------------------------------------------------------ */

typedef enum
{
    /* "Простые" однокадровые команды - у каждой ниже есть готовая
     * VESC_CAN_SendXxx() обёртка (см. секцию "Команды на веску"). */
    VESC_CAN_PACKET_SET_DUTY                   = 0,
    VESC_CAN_PACKET_SET_CURRENT                = 1,
    VESC_CAN_PACKET_SET_CURRENT_BRAKE          = 2,
    VESC_CAN_PACKET_SET_RPM                    = 3,
    VESC_CAN_PACKET_SET_POS                    = 4,
    VESC_CAN_PACKET_SET_CURRENT_REL            = 10,
    VESC_CAN_PACKET_SET_CURRENT_BRAKE_REL      = 11,
    VESC_CAN_PACKET_SET_CURRENT_HANDBRAKE      = 12,
    VESC_CAN_PACKET_SET_CURRENT_HANDBRAKE_REL  = 13,

    /**
     * Официальные коды протокола VESC для многокадровой пересылки
     * произвольных команд (используются мостом VESC Tool <-> CAN - см.
     * vesc_bridge.h/BRIDGE_PROTOCOL.md, а не VESC_CAN_SendXxx выше). Сами по
     * себе motor_vesc.c их не разбирает и не регистрирует под них фильтр -
     * это отдельный, независимый потребитель can_manager (см. vesc_bridge.h).
     */
    VESC_CAN_PACKET_FILL_RX_BUFFER             = 5,
    VESC_CAN_PACKET_FILL_RX_BUFFER_LONG        = 6,
    VESC_CAN_PACKET_PROCESS_RX_BUFFER          = 7,
    VESC_CAN_PACKET_PROCESS_SHORT_BUFFER       = 8,

    /* Статусные пакеты (телеметрия, VESC -> нас) */
    VESC_CAN_PACKET_STATUS      = 9,   /* ERPM, Current, Duty            */
    VESC_CAN_PACKET_STATUS_2    = 14,  /* Ah, Ah Charged                 */
    VESC_CAN_PACKET_STATUS_3    = 15,  /* Wh, Wh Charged                 */
    VESC_CAN_PACKET_STATUS_4    = 16,  /* Temp FET, Temp Motor, Iin, PID */

    /**
     * Официальные коды протокола VESC для проверки физического присутствия
     * на шине - см. VESC_CAN_RequestExists()/VESC_CAN_GetExistStatus() ниже.
     * PING адресуется конкретной веске как обычно ((PING << 8) | vesc_id),
     * но payload несёт НЕ пустое тело, а 1 байт - CAN ID отправителя
     * запроса; веска отвечает PONG-ом, адресованным ПО ЭТОМУ ID (а не по
     * своему собственному) - т.е. ответ приходит на ID запросившего, а не
     * запрошенного. Поэтому перед первым вызовом VESC_CAN_RequestExists()
     * нужно один раз задать "наш" ID через VESC_CAN_SetLocalId(). Сверено
     * построчно с comm_can.c прошивки VESC (comm_can_ping() и обработчик
     * CAN_PACKET_PING).
     */
    VESC_CAN_PACKET_PING        = 17,
    VESC_CAN_PACKET_PONG        = 18,

    VESC_CAN_PACKET_STATUS_5    = 27,  /* Tachometer, Vin                */
    VESC_CAN_PACKET_STATUS_6    = 58,  /* ADC1..3, PPM                   */

    /**
     * Статус №7 - НЕ входит в официальный протокол VESC. Это кастомный
     * пакет, который должен быть добавлен в прошивку вески отдельно (вы
     * сами модифицируете firmware).
     *
     * ID 200 (НЕ 59, как было до версии 1.6 - см. @warning ниже). Если в
     * прошивке вески уже используется другой номер, поменяйте здесь и в
     * vesc_ppm_universal.lisp (`can-status-id`).
     *
     * @warning До версии 1.6 здесь стоял ID 59 - "первый свободный после
     *          официальных статусов" на момент написания. С тех пор
     *          официальный протокол VESC разросся минимум до ID 68
     *          (включая CAN_PACKET_GNSS_TIME = 59 и CAN_PACKET_GNSS_LON =
     *          61 - оба реально заняты в актуальной прошивке!) - т.е. 59
     *          был живым коллизионным риском для любой вески с GNSS-модулем
     *          на CAN. Начиная с 1.6 кастомные ID перенесены в диапазон
     *          200+, оставляющий запас с обеих сторон. Если вы уже
     *          развернули более раннюю версию на реальном железе - при
     *          обновлении синхронно поменяйте ID в прошивке (Lisp-скрипт).
     *
     * Формат пакета (8 байт, как и у остальных статусов):
     *   byte[0] - флаг тормоза, int8_t: 0x01 - зажат, 0x02 - разжат, иначе/не
     *             приходило - VESC_BRAKE_STATE_NONE (см. VESC_BrakeState_t)
     *   byte[1] - флаг кастомного датчика, int8_t: 0x01 - pin-set, 0x02 -
     *             pin-reset, 0x00/иначе - VESC_CUSTOM_SENSOR_NONE (см.
     *             VESC_CustomSensorState_t)
     *   byte[2..7] - резерв (6 байт, для одинаковой длины со всеми
     *             остальными статусными пакетами)
     */
    VESC_CAN_PACKET_STATUS_7    = 200,

    /**
     * Команда №201 (была №60 до версии 1.6 - см. @warning у
     * VESC_CAN_PACKET_STATUS_7 выше, тот же коллизионный риск) - тоже НЕ
     * входит в официальный протокол VESC, парная к статусу №200
     * (обрабатывается тем же кастомным Lisp-скриптом на стороне вески).
     * Принудительное отпускание тормоза - см. VESC_CAN_SendReleaseBrake()
     * ниже.
     *
     * Формат пакета: 1 байт, значение 0x01 - "отпустить тормоз". Скрипт на
     * стороне вески держит отпущенное состояние по watchdog-таймауту (по
     * умолчанию 500 мс с момента последнего приёма этой команды) - чтобы
     * тормоз оставался отпущенным дольше, вызывающий код обязан звать
     * VESC_CAN_SendReleaseBrake() периодически сам, библиотека это за него
     * не делает (см. описание функции).
     */
    VESC_CAN_PACKET_CUSTOM_BRAKE_CMD = 201,

    /**
     * Команда №202 - НЕ входит в официальный протокол VESC. Явный запрос
     * "пришли мне кастомный статус X прямо сейчас, не дожидаясь следующего
     * периодического цикла" - см. VESC_CAN_RequestCustomStatus() ниже.
     * Payload: 1 байт - код запрашиваемого кастомного статуса (например
     * VESC_CAN_PACKET_STATUS_7). Поддерживается только если Lisp-скрипт на
     * стороне вески явно это реализует (см. секцию "Приём запроса кастомного
     * статуса" в vesc_ppm_universal.lisp) - для штатных статусов 1-6 такого
     * механизма в самой прошивке VESC нет (см. @warning у
     * VESC_CAN_RequestCustomStatus).
     */
    VESC_CAN_PACKET_CUSTOM_STATUS_REQUEST = 202,
} VESC_CAN_PacketId_t;

/* ------------------------------------------------------------------------ */
/*  Статус тормоза (кастомный статус №7, byte[0])                           */
/* ------------------------------------------------------------------------ */

typedef enum
{
    VESC_BRAKE_STATE_NONE     = 0, /* статус ещё не приходил, либо пришло не 0x01/0x02 -> тормоза нет / неизвестно */
    VESC_BRAKE_STATE_ENGAGED  = 1, /* флаг 0x01: тормоз зажат, вал зафиксирован (штатное состояние в покое)       */
    VESC_BRAKE_STATE_RELEASED = 2, /* флаг 0x02: тормоз разжат, вал может вращаться                              */
} VESC_BrakeState_t;

/* ------------------------------------------------------------------------ */
/*  Статус кастомного датчика (кастомный статус №7, byte[1])                */
/* ------------------------------------------------------------------------ */

typedef enum
{
    VESC_CUSTOM_SENSOR_NONE      = 0, /* флаг 0x00 (или статус ещё не приходил) - датчика нет / неизвестно */
    VESC_CUSTOM_SENSOR_PIN_SET   = 1, /* флаг 0x01 - pin-set   */
    VESC_CUSTOM_SENSOR_PIN_RESET = 2, /* флаг 0x02 - pin-reset */
} VESC_CustomSensorState_t;

/**
 * @brief  Тип функции-обработчика события кастомного датчика - см.
 *         VESC_CAN_SetCustomSensorCallback().
 *
 * @warning Вызывается ИЗ ПРЕРЫВАНИЯ (изнутри диспетчеризации can_manager -
 *          `CANMGR_RxFifo_Handler`, в контексте приёма CAN-кадра) -
 *          обработчик должен быть быстрым и НЕ блокирующим: никаких
 *          HAL_Delay()/долгих вычислений/ожиданий внутри, аккуратно с
 *          данными, общими с основным кодом программы (volatile-флаги,
 *          критические секции при необходимости - как в любом другом коде,
 *          вызываемом из ISR на STM32).
 *
 * @param  h  хэндл вески, от которой пришёл статус (тот же, что вернул
 *            VESC_CAN_Init() для неё) - через h->telemetry.custom_sensor_state
 *            обработчик может прочитать актуальное значение (pin-set/pin-reset).
 */
typedef void (*VESC_CustomSensorCallback_t)(VESC_Handle_t *h);

/**
 * @brief  Тип функции-обработчика приёма ЛЮБОГО статусного пакета телеметрии -
 *         см. VESC_CAN_SetTelemetryCallback(). В отличие от
 *         VESC_CustomSensorCallback_t (который реагирует только на кастомный
 *         датчик), этот вызывается на КАЖДЫЙ распознанный статусный пакет
 *         (VESC_CAN_PACKET_STATUS, STATUS_2 .. STATUS_7) - удобно, если
 *         остальной части программы нужно узнавать о приёме телеметрии сразу,
 *         не дожидаясь следующего опроса своего кода (например, чтобы
 *         немедленно скорректировать общий пакет телеметрии системы или
 *         переслать данные ещё куда-то).
 *
 * @warning Для реальной вески вызывается ИЗ ПРЕРЫВАНИЯ (изнутри
 *          диспетчеризации can_manager - `CANMGR_RxFifo_Handler`, в
 *          контексте приёма CAN-кадра). Для имитируемой вески (см.
 *          VESC_CAN_SetSimulated) вызывается из
 *          того же контекста, откуда вызвана VESC_CAN_SimulateTick() -
 *          на практике это тоже обычно прерывание таймера. В обоих
 *          случаях уже ПОСЛЕ того как телеметрия хэндла обновлена (данные
 *          соответствующего статуса уже можно читать из h->telemetry) -
 *          обработчик должен быть быстрым и НЕ блокирующим: никаких
 *          HAL_Delay()/долгих вычислений/ожиданий внутри, аккуратно с
 *          данными, общими с основным кодом программы (volatile-флаги,
 *          критические секции при необходимости - как в любом другом
 *          коде, вызываемом из ISR на STM32).
 *
 * @param  h          хэндл вески, от которой пришёл статус (тот же, что
 *                     вернул VESC_CAN_Init() для неё)
 * @param  status_id  какой именно статусный пакет только что разобран -
 *                     одно из значений VESC_CAN_PacketId_t с префиксом
 *                     VESC_CAN_PACKET_STATUS* (какие именно поля telemetry
 *                     свежие после этого статуса - см. комментарии у полей
 *                     VESC_Telemetry_t, сгруппированные по номеру пакета)
 */
typedef void (*VESC_TelemetryCallback_t)(VESC_Handle_t *h, VESC_CAN_PacketId_t status_id);

/**
 * @brief  Тип функции-обработчика ПРОИЗВОЛЬНОЙ (кастомной) команды/статуса от
 *         вески - см. VESC_CAN_SetCustomCommandCallback() и секцию
 *         "Произвольные кастомные команды" ниже. Вызывается на любой принятый
 *         Extended-кадр, у которого CAN ID соответствует ЗАРЕГИСТРИРОВАННОЙ
 *         веске (`h`), но код команды (`custom_cmd_id`, биты 15-8 ID) НЕ входит
 *         в набор, который библиотека распознаёт сама (`VESC_CAN_PACKET_STATUS`
 *         .. `STATUS_7`) - то есть именно та ситуация, когда вы сами (или ваш
 *         Lisp-скрипт на стороне вески) придумали свой формат обмена сверх
 *         штатного протокола VESC. Парная функция для отправки - см.
 *         VESC_CAN_SendCustomCommand().
 *
 * @warning Вызывается ИЗ ПРЕРЫВАНИЯ (изнутри диспетчеризации can_manager -
 *          `CANMGR_RxFifo_Handler`, в контексте приёма CAN-кадра) -
 *          обработчик должен быть быстрым и НЕ блокирующим: никаких
 *          HAL_Delay()/долгих вычислений/ожиданий внутри, аккуратно с
 *          данными, общими с основным кодом программы (volatile-флаги,
 *          критические секции при необходимости).
 *
 * @param  h              хэндл вески, от которой пришёл кадр
 * @param  custom_cmd_id  код команды как есть (0..255) - ваш собственный,
 *                         не входящий в VESC_CAN_PacketId_t
 * @param  data           данные кадра, валидны только на время вызова
 *                         (используйте/скопируйте внутри обработчика)
 * @param  len            реальная длина данных, байт (0..8) - НЕ читайте
 *                         data за пределами этой длины, остаток буфера не
 *                         инициализирован
 */
typedef void (*VESC_CustomCommandCallback_t)(VESC_Handle_t *h, uint8_t custom_cmd_id,
                                              const uint8_t *data, uint8_t len);

/* ------------------------------------------------------------------------ */
/*  Произвольные кастомные СТАТУСЫ (масштабируемо, не только STATUS_7)      */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Тип функции-обработчика ОДНОГО зарегистрированного кастомного
 *         статуса - см. VESC_CAN_RegisterCustomStatus(). В отличие от
 *         VESC_CustomCommandCallback_t (один общий колбэк на ВСЕ незнакомые
 *         коды сразу, разбор кода делаете сами внутри), здесь у каждого
 *         кастомного статуса СВОЙ отдельный колбэк - библиотека сама
 *         сверяет код пакета и вызывает только нужный, парсинг конкретного
 *         payload при этом можно держать в отдельном файле вашего проекта
 *         (обработчик - обычная функция, ей всё равно, откуда её вызвали).
 *
 * @warning Вызывается ИЗ ПРЕРЫВАНИЯ (изнутри диспетчеризации can_manager -
 *          `CANMGR_RxFifo_Handler`) - обработчик должен быть быстрым и НЕ
 *          блокирующим, как и VESC_CustomCommandCallback_t выше.
 *
 * @param  h        хэндл вески, от которой пришёл статус
 * @param  cmd_id   код статуса как есть - тот же, что передан в
 *                   VESC_CAN_RegisterCustomStatus() при регистрации
 * @param  data     данные кадра, валидны только на время вызова
 * @param  len      реальная длина данных, байт (0..8)
 */
typedef void (*VESC_CustomStatusCallback_t)(VESC_Handle_t *h, uint8_t cmd_id,
                                             const uint8_t *data, uint8_t len);

/* ------------------------------------------------------------------------ */
/*  Телеметрия одной вески (результат разбора 7 статусных пакетов)          */
/* ------------------------------------------------------------------------ */

typedef struct
{
    /* CAN_PACKET_STATUS */
    float    erpm;                 /* электрические RPM (как есть в кадре VESC, без пересчёта) */
    float    mech_rpm;             /* = erpm / pole_pairs, механические (реальные, "на валу") RPM -
                                     * см. VESC_Config_t.pole_count. Считается автоматически. */
    float    current;              /* A                                  */
    float    duty;                 /* 0..1                               */

    /* CAN_PACKET_STATUS_2 */
    float    amp_hours;            /* Ah                                  */
    float    amp_hours_charged;    /* Ah                                  */

    /* CAN_PACKET_STATUS_3 */
    float    watt_hours;           /* Wh                                  */
    float    watt_hours_charged;   /* Wh                                  */

    /* CAN_PACKET_STATUS_4 */
    float    temp_fet;             /* °C                                  */
    float    temp_motor;           /* °C                                  */
    float    current_in;           /* A                                   */
    float    pid_pos;              /* градусы. Если включена "память положения"
                                     * (см. VESC_CAN_SetPositionMemoryEnabled) - это
                                     * УЖЕ скорректированное офсетом значение, "чистый"
                                     * pid_pos из кадра нигде наружу не отдаётся. */

    /* CAN_PACKET_STATUS_5 */
    float    tachometer;           /* EREV                                */
    float    v_in;                 /* V                                   */

    /* CAN_PACKET_STATUS_6 */
    float    adc1;
    float    adc2;
    float    adc3;
    float    ppm;

    /* CAN_PACKET_STATUS_7 (кастомный) */
    VESC_BrakeState_t        brake_state;
    VESC_CustomSensorState_t custom_sensor_state; /* см. VESC_CAN_SetCustomSensorCallback ниже.
                                                     * У имитируемых весок (VESC_CAN_SetSimulated)
                                                     * всегда остаётся VESC_CUSTOM_SENSOR_NONE - для
                                                     * произвольного внешнего датчика нет обобщённой
                                                     * модели поведения, которую можно было бы
                                                     * честно имитировать. */

    uint32_t last_rx_tick;         /* HAL_GetTick() последнего любого статуса */
    uint16_t rx_mask;              /* битовая маска: какие из 7 пакетов приходили хотя бы раз */
} VESC_Telemetry_t;

/* Биты rx_mask (bit0..bit6 = STATUS..STATUS_7) */
#define VESC_CAN_RXMASK_STATUS      (1U << 0)
#define VESC_CAN_RXMASK_STATUS_2    (1U << 1)
#define VESC_CAN_RXMASK_STATUS_3    (1U << 2)
#define VESC_CAN_RXMASK_STATUS_4    (1U << 3)
#define VESC_CAN_RXMASK_STATUS_5    (1U << 4)
#define VESC_CAN_RXMASK_STATUS_6    (1U << 5)
#define VESC_CAN_RXMASK_STATUS_7    (1U << 6)
#define VESC_CAN_RXMASK_ALL         (0x7FU)

/* ------------------------------------------------------------------------ */
/*  Одна "отложенная" команда в программной очереди вески (см. ниже)        */
/* ------------------------------------------------------------------------ */

typedef struct
{
    volatile uint8_t   valid;    /* слот занят (есть что досылать)   */
    volatile uint8_t   cmd_id;   /* VESC_CAN_PacketId_t команды      */
    volatile int32_t   value;    /* уже промасштабированное значение */
} VESC_PendingCmd_t;

/* ------------------------------------------------------------------------ */
/*  Проверка физического присутствия на шине (PING/PONG)                    */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Результат проверки "веска физически существует на шине" - см.
 *         VESC_CAN_RequestExists()/VESC_CAN_GetExistStatus().
 */
typedef enum
{
    VESC_EXIST_UNKNOWN   = 0, /* VESC_CAN_RequestExists() ещё не вызывался */
    VESC_EXIST_PENDING   = 1, /* запрос отправлен, ответа нет, таймаут ЕЩЁ НЕ истёк */
    VESC_EXIST_CONFIRMED = 2, /* PONG получен - веска на шине физически есть */
    VESC_EXIST_TIMEOUT   = 3, /* таймаут (VESC_CAN_EXIST_TIMEOUT_MS) истёк, ответа не было */
} VESC_ExistStatus_t;

/* ------------------------------------------------------------------------ */
/*  Один слот реестра кастомных статусов (см. VESC_CAN_RegisterCustomStatus) */
/* ------------------------------------------------------------------------ */

typedef struct
{
    uint8_t                     used;     /* слот занят */
    uint8_t                     cmd_id;   /* какой код пакета сюда назначен */
    VESC_CustomStatusCallback_t callback; /* см. VESC_CustomStatusCallback_t, не NULL если used */
} VESC_CustomStatusSlot_t;

