/*  Хэндл вески - главная структура API                                     */
/* ------------------------------------------------------------------------ */
/*
 * VESC_CAN_Init() возвращает указатель НА ЭТУ структуру (память статическая,
 * живёт всё время работы программы - НЕ нужно её создавать/освобождать
 * самостоятельно, только хранить полученный указатель у себя).
 *
 * Поля, с которыми предполагается работать СНАРУЖИ модуля:
 *   - bus, vesc_id    - только чтение, для справки/логирования (bus - тот же
 *                        указатель CANMGR_Handle_t*, что был передан в config)
 *   - telemetry       - только чтение, актуальные данные обновляются сами
 *                        по мере прихода статусных CAN-кадров (диспетчеризуются
 *                        can_manager-ом в зарегистрированный этим модулем
 *                        callback); используйте telemetry.* напрямую,
 *                        отдельная функция-геттер не нужна
 *
 * Остальные поля - ВНУТРЕННЕЕ состояние модуля (программная очередь команд,
 * настройки "губернаторов", состояние имитации). Структура объявлена целиком
 * (а не как непрозрачный тип) ради простоты и скорости (без malloc, без
 * скрытых аллокаций), но эти поля напрямую трогать не нужно - меняйте их
 * только через API-функции (VESC_CAN_SetSpeedLimit и т.п.).
 */
struct VESC_Handle_s
{
    /* ---- Публичные поля (только чтение) ---- */
    CANMGR_Handle_t  *bus;      /* шина (can_manager), на которой зарегистрирована веска -
                                  * было hcan/VESC_CAN_HandleTypeDef* до миграции на can_manager */
    uint8_t           vesc_id;  /* CAN ID вески                            */
    VESC_Telemetry_t  telemetry; /* актуальная телеметрия (обновляется сама) */

    /* ---- Внутреннее состояние модуля - не трогать напрямую ---- */
    uint8_t             used;   /* слот занят (внутренняя бухгалтерия пула) */

    VESC_PendingCmd_t   pending[VESC_CAN_MAX_PENDING_PER_VESC];

    uint8_t             speed_limit_enabled;
    float               speed_limit;          /* |RPM|, см. VESC_CAN_SetSpeedLimit */
    float               speed_limit_margin;    /* полоса губернатора тока по скорости */
    uint8_t             current_limit_enabled;
    float               current_limit;         /* |A|, см. VESC_CAN_SetCurrentLimit */
    float               current_limit_margin;  /* полоса губернатора скорости по току */

    VESC_CustomSensorCallback_t  custom_sensor_callback;  /* см. VESC_CAN_SetCustomSensorCallback, NULL по умолчанию */
    VESC_TelemetryCallback_t     telemetry_callback;      /* см. VESC_CAN_SetTelemetryCallback, NULL по умолчанию    */
    VESC_CustomCommandCallback_t custom_command_callback; /* см. VESC_CAN_SetCustomCommandCallback, NULL по умолчанию */

    VESC_CustomStatusSlot_t custom_statuses[VESC_CAN_MAX_CUSTOM_STATUSES]; /* см. VESC_CAN_RegisterCustomStatus */

    VESC_ExistStatus_t  exist_status;    /* см. VESC_CAN_RequestExists/GetExistStatus, VESC_EXIST_UNKNOWN по умолчанию */
    uint32_t            ping_sent_tick;  /* HAL_GetTick() последнего VESC_CAN_RequestExists() */

#if VESC_CAN_SIM_ENABLE
    uint8_t             simulated;          /* 1 - веска фейковая, данные генерируются программно */
    int32_t             last_commanded_rpm; /* последняя скорость, отправленная через VESC_CAN_SendSpeed - вход модели имитации */
#endif

    uint8_t             pole_pairs;   /* = pole_count/2 из конфига, закэшировано для быстрого пересчёта ERPM<->mech_rpm */

#if defined(HAL_RTC_MODULE_ENABLED)
    uint8_t              position_memory_enabled;         /* см. VESC_CAN_SetPositionMemoryEnabled */
    uint8_t              position_memory_pending_restore; /* включили, но ещё ни разу не приходил STATUS_4 - офсет посчитаем на первом же */
    RTC_HandleTypeDef    *position_memory_hrtc;            /* из config, см. VESC_Config_t            */
    uint32_t              position_memory_backup_index;    /* из config, см. VESC_Config_t            */
    float                 position_offset_deg;             /* текущий вычисленный офсет                */
    float                 last_raw_pid_pos;                 /* последнее СЫРОЕ (без офсета) значение pid_pos */
#endif
};

/* ------------------------------------------------------------------------ */
/*  Конфигурация для регистрации вески                                      */
/* ------------------------------------------------------------------------ */

typedef struct
{
    /** Шина (can_manager), на которой сидит эта веска - указатель, полученный
     *  из CANMGR_Init() (см. can_manager.h), а не сырой HAL-хэндл периферии
     *  (было VESC_CAN_HandleTypeDef* hcan до миграции на can_manager). */
    CANMGR_Handle_t *bus;

    /** CAN ID вески (0..255, задаётся в VESC Tool: App Settings -> General
     *  -> VESC ID). Один и тот же id допустим на РАЗНЫХ шинах одновременно -
     *  это разные физические вески, каждая получит свой VESC_Handle_t. */
    uint8_t vesc_id;

    /** Число полюсов мотора (не пар полюсов, а именно полюсов - чётное
     *  число, например 14 для типичного BLDC-мотора с 14 полюсами/12 пазами).
     *  Обязательное поле - используется для пересчёта между "сырыми"
     *  электрическими RPM протокола VESC (erpm) и механическими RPM на валу
     *  (mech_rpm = erpm / (pole_count/2)) - см. VESC_CAN_SendMechanicalSpeed
     *  и telemetry.mech_rpm. Если это поле неважно для вашей задачи и вы
     *  работаете только в электрических RPM - укажите 2 (тогда mech_rpm ==
     *  erpm, пересчёт становится тождественным). */
    uint8_t pole_count;

#if defined(HAL_RTC_MODULE_ENABLED)
    /** Опционально: хэндл RTC для "памяти положения" (см.
     *  VESC_CAN_SetPositionMemoryEnabled ниже). Нужен, только если будете
     *  включать эту функцию для данной вески - если не планируете, оставьте
     *  NULL. RTC должен быть проинициализирован в CubeMX с тактированием от
     *  LSE (внешний часовой кварц) при наличии батарейки на VBAT - иначе
     *  backup-регистры переживут только сброс/сон, но НЕ полное обесточивание
     *  платы, см. подробное пояснение в секции "Память положения" ниже. */
    RTC_HandleTypeDef *position_memory_hrtc;

    /** Индекс backup-регистра RTC (RTC_BKP_DR0, RTC_BKP_DR1, ...), с которого
     *  начинается хранение данных ЭТОЙ вески. Функция резервирует ДВА
     *  ПОДРЯД идущих регистра (сам этот индекс и index+1) - разным вескам
     *  ОБЯЗАТЕЛЬНО назначайте непересекающиеся индексы вручную (модуль это
     *  не проверяет и не может проверить - у разных весок нет общего
     *  реестра занятых регистров). STM32F4: доступно 20 регистров (0..19,
     *  т.е. максимум 10 весок с этой функцией на чип). STM32H7: 32 регистра
     *  (0..31, до 16 весок). */
    uint32_t position_memory_backup_index;
#endif
} VESC_Config_t;

