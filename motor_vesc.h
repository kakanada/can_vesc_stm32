/** Включает губернатор тока: прямой clamp для SendCurrent/SendCurrentBrake/
 *  SendHandbrakeCurrent и перекрёстный (по телеметрии) потолок для
 *  VESC_CAN_SendSpeed. governor_margin_current - полоса сглаживания
 *  перекрёстного губернатора. */
HAL_StatusTypeDef VESC_CAN_SetCurrentLimit(VESC_Handle_t *h, float max_abs_current, float governor_margin_current);

/** Снимает ограничение, установленное VESC_CAN_SetCurrentLimit(). */
HAL_StatusTypeDef VESC_CAN_ClearCurrentLimit(VESC_Handle_t *h);

/* ------------------------------------------------------------------------ */
/*  Память положения между включениями вески (backup-регистры RTC)          */
/* ------------------------------------------------------------------------ */
/*
 * ЗАЧЕМ ЭТО НУЖНО:
 * веска с датчиками Холла определяет положение вала внутри одного
 * электрического периода, но после выключения/включения питания вески это
 * значение может "съехать" (мотор физически не повернулся, а pid_pos на
 * старте показывает другое число) - привязки к абсолютной системе координат,
 * в которой работал до выключения, не остаётся. Эта секция - способ
 * восстановить эту привязку силами STM32, не трогая саму веску.
 *
 * КАК ЭТО РАБОТАЕТ:
 *   - Пока функция включена (VESC_CAN_SetPositionMemoryEnabled(h, 1)), при
 *     каждом новом статусе STATUS_4 модуль запоминает СКОРРЕКТИРОВАННОЕ
 *     значение pid_pos (raw_pid_pos + offset) в backup-регистры RTC - это
 *     дёшево (не флеш, ресурс перезаписи практически не ограничен) и
 *     доступно даже когда основное питание платы снято, если на VBAT висит
 *     батарейка (именно поэтому используются backup-регистры, а не флеш).
 *   - При включении функции (или при первом же кадре STATUS_4, если на
 *     момент включения свежих данных ещё не было) модуль читает последнее
 *     сохранённое значение из backup и вычисляет offset = сохранённое -
 *     raw_pid_pos_только_что_принятый, так что скорректированное значение в
 *     этот момент точно равно сохранённому - то есть "подхватывает" систему
 *     координат с того места, где она была до выключения.
 *   - h->telemetry.pid_pos, пока функция включена, ВСЕГДА уже с учётом
 *     офсета - "сырое" значение из кадра наружу нигде не отдаётся.
 *
 * ЧЕСТНО про backup-регистры RTC (важно прочитать перед использованием):
 *   - Это НЕ EEPROM и не флеш. Backup-регистры RTC (домен VBAT) переживают
 *     сброс МК и переход в низкопотребляющие режимы ВСЕГДА, а вот полное отключение
 *     ОСНОВНОГO питания платы - только если на вывод VBAT заведена батарейка
 *     (обычно CR2032 через диод, стандартная схема для RTC). Без батарейки
 *     на VBAT при полном обесточивании платы содержимое backup-регистров
 *     потеряется - то есть ваш сценарий "выключили веску, но STM32 при этом
 *     тоже обесточился" будет работать ТОЛЬКО с батарейкой на VBAT. Если
 *     STM32 в вашей схеме не обесточивается вместе с веской (питается
 *     отдельно и постоянно) - батарейка не обязательна, backup-регистры и
 *     так переживут это без неё.
 *   - Модуль вызывает HAL_PWR_EnableBkUpAccess() сам (перед первой записью),
 *     но RTC (HAL_RTC_Init с тактированием от LSE или LSI) должен быть уже
 *     настроен в CubeMX - модуль его не настраивает и не запускает.
 *   - Функция доступна, только если в проекте включён HAL_RTC_MODULE_ENABLED
 *     (RTC используется где-то в проекте). Если это не так - объявления
 *     ниже всё равно скомпилируются (не нужно их вырезать из кода), но
 *     реально ничего не делают и всегда возвращают HAL_ERROR - см. .c файл.
 *   - Функция резервирует ДВА backup-регистра на веску (см.
 *     VESC_Config_t.position_memory_backup_index) - следите за
 *     пересечениями индексов сами при нескольких вескими.
 */

/**
 * @brief  Включает/выключает память положения для вески (см. секцию выше).
 *         При ВКЛЮЧЕНИИ читает backup-регистр и сразу же (если уже есть
 *         хоть один принятый STATUS_4) либо при следующем принятом STATUS_4
 *         (если ещё не было) - вычисляет офсет так, чтобы продолжить с того
 *         места, на котором остановились. При ВЫКЛЮЧЕНИИ - telemetry.pid_pos
 *         возвращается к "сырому" значению без коррекции.
 *
 * @param  h        хэндл вески
 * @param  enabled  1 - включить, 0 - выключить
 * @retval HAL_OK; HAL_ERROR если h == NULL, либо если
 *         config.position_memory_hrtc не был задан при VESC_CAN_Init(),
 *         либо если HAL_RTC_MODULE_ENABLED не включён в проекте.
 */
HAL_StatusTypeDef VESC_CAN_SetPositionMemoryEnabled(VESC_Handle_t *h, uint8_t enabled);

/**
 * @brief  Ручная калибровка "на лету": говорит модулю "прямо сейчас реальный
 *         угол вала - вот такой", пересчитывает офсет соответствующим
 *         образом и сразу сохраняет скорректированное значение в backup.
 *         Пригодится, если система координат разошлась (например после
 *         механического вмешательства) и нужно её переустановить вручную.
 *         Требует, чтобы память положения была настроена в конфиге (hrtc
 *         задан) - включать VESC_CAN_SetPositionMemoryEnabled() отдельно не
 *         обязательно, эта функция сама неявно её включает.
 *
 * @param  h                   хэндл вески
 * @param  actual_position_deg реальный угол вала прямо сейчас, градусы 0..360
 * @retval HAL_OK; HAL_ERROR если h == NULL, память положения не настроена в
 *         конфиге, либо ещё ни разу не приходил STATUS_4 (не от чего
 *         считать офсет - подождите первую телеметрию)
 */
HAL_StatusTypeDef VESC_CAN_SetCurrentPosition(VESC_Handle_t *h, float actual_position_deg);

