/**
 * @brief  Счётчик отвергнутых входящих внешних пакетов (несовпадение CRC16,
 *         неверный стоп-байт, переполнение VESC_BRIDGE_MAX_PAYLOAD, таймаут
 *         незавершённого пакета) с момента создания моста. В штатной работе
 *         должен оставаться на 0 или расти очень редко (единичные сбои
 *         транспорта) - постоянный рост означает проблему на стороне
 *         транспорта (обрыв TCP, шум на UART) либо VESC_BRIDGE_MAX_PAYLOAD
 *         меньше, чем реально нужно.
 * @param  br  мост
 * @retval счётчик, либо 0 если br == NULL
 */
uint32_t VESC_Bridge_GetRxErrorCount(VESC_Bridge_t *br);

/**
 * @brief  Счётчик отвергнутых ответов от весок по CAN (несовпадение CRC16
 *         собранного буфера в CAN_PACKET_PROCESS_RX_BUFFER) с момента
 *         создания моста. В штатной работе должен оставаться на 0 - рост
 *         означает потерю CAN-кадров в процессе сборки многокадрового ответа
 *         (см. VESC_CAN_GetRxOverflowCount/GetBusOffCount в motor_vesc.h -
 *         вероятная связанная причина).
 * @param  br  мост
 * @retval счётчик, либо 0 если br == NULL
 */
uint32_t VESC_Bridge_GetCanCrcErrorCount(VESC_Bridge_t *br);

