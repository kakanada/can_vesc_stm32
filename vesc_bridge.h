/** Максимальное число одновременно существующих мостов (например, отдельный
 *  мост на Ethernet и отдельный на UART/VCP одновременно, на одной или на
 *  разных CAN-шинах). */
#ifndef VESC_BRIDGE_MAX_INSTANCES
#define VESC_BRIDGE_MAX_INSTANCES        2U
#endif

/** Максимальный размер payload ОДНОЙ команды VESC Tool (в любую сторону) в
 *  байтах - им ограничен и буфер приёма внешнего кадра, и буфер пересборки
 *  многокадрового CAN-ответа. Рассчитан на конфигурационные пакеты
 *  (GET/SET MCCONF/APPCONF и т.п.), НЕ на прошивку весок - см. описание
 *  файла выше и BRIDGE_PROTOCOL.md. Увеличивайте при нехватке (например если
 *  ваша версия MCCONF/APPCONF больше), помня о цене в статической памяти -
 *  ПЯТЬ буферов такого размера на КАЖДЫЙ VESC_Bridge_t (приём внешнего
 *  кадра, копия форвардимой команды, пересборка CAN-ответа, ДВА исходящих
 *  кадра - см. @warning у vesc_bridge_send_framed_buf() в vesc_bridge.c про
 *  отдельный буфер для CAN RX ISR с версии 1.13) - см. VESC_BRIDGE_MAX_INSTANCES.
 *  При значении по умолчанию (1024) это ~5 КБ на мост, ~10 КБ при двух
 *  одновременных мостах (плюс отдельно очередь форвардинга, см.
 *  VESC_BRIDGE_FORWARD_QUEUE_BYTES). */
#ifndef VESC_BRIDGE_MAX_PAYLOAD
#define VESC_BRIDGE_MAX_PAYLOAD          1024U
#endif
#if VESC_BRIDGE_MAX_PAYLOAD > 65535U
#error "vesc_bridge: VESC_BRIDGE_MAX_PAYLOAD не может превышать 65535 - длина payload во внешнем кадрировании (packet.c) кодируется 16 битами"
#endif

/** [v1.12] НЕ ЗАДЕРЖИВАЕТ запуск следующего форвардинга из очереди (это
 *  было так в 1.11 - больше нет, см. @note у vesc_bridge_fwd_phase_t в
 *  vesc_bridge.c, форвардинг теперь fire-and-forget по образцу настоящего
 *  VESC Express). Единственное оставшееся назначение - окно, в течение
 *  которого VESC_Bridge_IsTargetActive() считает веску "активной" ПОСЛЕ
 *  последнего успешно отправленного в её сторону кадра форвардинга - чтобы
 *  вызывающий код мог придержать штатные команды (VESC_CAN_SendXxx) именно
 *  этой веске, пока она, вероятно, ещё обрабатывает форвардированный запрос
 *  и может прислать ответ. Оценочное значение, не измерялось на реальной
 *  задержке VESC Tool <-> мост <-> CAN <-> veska. */
#ifndef VESC_BRIDGE_FORWARD_TIMEOUT_MS
#define VESC_BRIDGE_FORWARD_TIMEOUT_MS   500U
#endif

/* [v1.14] VESC_BRIDGE_RX_TIMEOUT_MS (глобальный #define) УДАЛЁН - таймаут разбора
 * НЕЗАВЕРШЁННОГО внешнего кадра теперь задаётся в VESC_Bridge_Config_t.rx_timeout_ms
 * (0 = выключен) - см. там же рекомендации по транспортам (TCP/UART). */

/** Сколько кадров CAN_PACKET_PING слать за ОДИН вызов VESC_Bridge_Tick() при
 *  активном скане шины (см. COMM_PING_CAN/VESC_Bridge_Tick) - ограничивает
 *  разовую нагрузку на программную очередь can_manager (см. CANMGR_TX_QUEUE_SIZE
 *  в can_manager.h), остаток кандидатов (0..254) добивается на следующих
 *  тиках. Если очередь can_manager занята прямо сейчас - отправка тоже просто
 *  переносится на следующий тик (см. CANMGR_Send). */
#ifndef VESC_BRIDGE_SCAN_PINGS_PER_TICK
#define VESC_BRIDGE_SCAN_PINGS_PER_TICK  16U
#endif

/** Сколько ждать (мс) PONG-ответов ПОСЛЕ того, как отправлен последний
 *  CAN_PACKET_PING скана (см. COMM_PING_CAN), прежде чем считать скан
 *  завершённым и отправить VESC Tool собранный список ID. С запасом меньше
 *  таймаута самого VESC Tool на ответ COMM_PING_CAN (по имеющимся данным
 *  порядка 500 мс) - см. BRIDGE_PROTOCOL.md. */
#ifndef VESC_BRIDGE_SCAN_SETTLE_MS
#define VESC_BRIDGE_SCAN_SETTLE_MS       150U
#endif

/** [v1.12] Размер (в байтах) кольцевого буфера очереди форвардинга
 *  (COMM_FORWARD_CAN), ожидающих отправки ПОМИМО того, что прямо сейчас
 *  отправляется - см. §3 BRIDGE_PROTOCOL.md. VESC Tool конвейерит запросы
 *  (например SET_MCCONF и следом GET_MCCONF для read-back, не дожидаясь
 *  ответа на первый; либо до десятка мелких команд одним пакетом) - без
 *  очереди новый запрос раньше либо перезаписывал ещё не отправленный
 *  старый, либо (v1.11) ждал ответа вески перед стартом следующего, что НЕ
 *  соответствует поведению настоящего VESC Express (там форвардинг - fire-
 *  and-forget, см. @note у vesc_bridge_fwd_phase_t в vesc_bridge.c).
 *
 *  Каждая запись в кольце - [target_id:1][len:2][payload:len] байт -
 *  типичная команда занимает единицы байт, SET_MCCONF/APPCONF - сотни, то
 *  есть при значении по умолчанию (4096) влезает одновременно и пара
 *  десятков мелких команд, и один-два больших конфигурационных пакета.
 *  Переполнение - НОВЫЙ запрос, для которого не хватило места, целиком
 *  ОТБРАСЫВАЕТСЯ (см. VESC_Bridge_GetForwardQueueOverflowCount) - уже
 *  стоящие в очереди запросы не трогаются. */
#ifndef VESC_BRIDGE_FORWARD_QUEUE_BYTES
#define VESC_BRIDGE_FORWARD_QUEUE_BYTES  4096U
#endif

/** [v1.16] Через сколько мс после форвардинга чтения/записи конфигурации
 *  (GET/SET MCCONF/APPCONF) и блока прошивки без ответа вески в лог пишется
 *  LOG_CODE_VESC_BR_REPLY_TIMEOUT. Только для лога (VESC_ENABLE_LOGGER), на
 *  работу моста не влияет. Стирание прошивки (ERASE_NEW_APP) не отслеживается -
 *  оно легально занимает секунды. */
#ifndef VESC_BRIDGE_REPLY_TIMEOUT_MS
#define VESC_BRIDGE_REPLY_TIMEOUT_MS     1000U
#endif

