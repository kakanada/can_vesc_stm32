/**
 * Хэндл одного моста. В ОТЛИЧИЕ от VESC_Handle_t (motor_vesc.h), это
 * непрозрачный (opaque) тип - у моста нет полей, с которыми предполагается
 * работать напрямую (всё через функции ниже), поэтому полное определение
 * структуры спрятано в vesc_bridge.c. Как и VESC_Handle_t, живёт в
 * статической памяти модуля (пул на VESC_BRIDGE_MAX_INSTANCES) - не нужно
 * его создавать/освобождать, только хранить полученный из VESC_Bridge_Init()
 * указатель у себя.
 */
typedef struct VESC_Bridge_s VESC_Bridge_t;

/**
 * @brief  Колбэк "отправь эти байты клиенту (VESC Tool)". Вызывается ИЗНУТРИ
 *         VESC_Bridge_FeedBytes()/VESC_Bridge_OnCanFrame() - в ТОМ ЖЕ
 *         контексте (стеке вызовов), из которого вы сами вызвали одну из
 *         этих функций (никакой отдельной задачи/потока модуль не создаёт).
 *         Реализация - целиком ваша (send() в TCP-сокет, HAL_UART_Transmit
 *         /_DMA, CDC_Transmit_FS и т.п.) - см. примеры в README.md под
 *         каждый из 4 сценариев подключения.
 *
 * @warning [v1.13, подтверждено тестированием на реальном железе] Через
 *          VESC_Bridge_OnCanFrame() этот колбэк вызывается ИЗ CAN RX
 *          ПРЕРЫВАНИЯ (ответы вески диспетчеризуются can_manager-ом из
 *          `CANMGR_RxFifo_Handler`, см. @warning у VESC_Bridge_OnCanFrame
 *          ниже) - НЕ из основного цикла, даже если ваш транспорт сам
 *          устроен так, что VESC_Bridge_FeedBytes() вы вызываете только из
 *          main. Блокирующие/тяжёлые операции ИЗ ЭТОГО КОЛБЭКА В ЭТОМ
 *          СЛУЧАЕ (например lwIP tcp_write()/tcp_output() напрямую, без
 *          потокобезопасной обвязки) НЕБЕЗОПАСНЫ - стек lwIP (как и многие
 *          другие) не рассчитан на вызов из произвольного прерывания.
 *          Рекомендуемый паттерн (проверен тестовой сессией на реальном
 *          стенде): колбэк копирует переданные байты в свой собственный
 *          кольцевой буфер под защитой PRIMASK-save/restore (НЕ безусловный
 *          __enable_irq() в конце - см. @warning у vesc_bridge_forward_step()
 *          в vesc_bridge.c за объяснением, почему это важно при вложенных
 *          критических секциях) и сразу возвращается; реальная отправка в
 *          транспорт (tcp_write и т.п.) - из основного цикла, который
 *          опустошает этот кольцевой буфер. См. также VESC_EXPRESS_GUIDE.md.
 *
 * @param  br    мост, который просит отправить байты
 * @param  data  указатель на буфер для отправки - валиден ТОЛЬКО на время
 *               вызова колбэка (внутренний буфер модуля, переиспользуется
 *               при следующем ответе ПО ТОМУ ЖЕ пути - см. @warning выше про
 *               раздельные буферы ISR/не-ISR пути, но даже так валиден
 *               только на время вызова) - если ваш транспорт отправляет
 *               асинхронно (DMA, неблокирующий сокет) и не может скопировать
 *               данные СРАЗУ - скопируйте их в свой собственный буфер внутри
 *               колбэка, прежде чем возвращаться из него
 * @param  len   длина данных, байт
 */
typedef void (*VESC_Bridge_TxCallback_t)(VESC_Bridge_t *br, const uint8_t *data, uint16_t len);

/**
 * @brief  "Тип железа" для локального ответа на COMM_FW_VERSION (см. hw_type
 *         в VESC_Bridge_Config_t) - подмножество enum HW_TYPE_xxx из
 *         прошивки VESC/VESC Express, по которому VESC Tool решает, чего
 *         ожидать от подключённого устройства (мотор/MCCONF у самого
 *         устройства или нет).
 *
 * @warning VESC_BRIDGE_HW_TYPE_VESC (0) - значение по умолчанию при
 *          неинициализированной (memset-нулём) конфигурации, ради обратной
 *          совместимости с версиями библиотеки до 1.9 (где это было
 *          единственное зашитое значение). ДЛЯ ХАБА БЕЗ СОБСТВЕННОГО МОТОРА
 *          (типичный сценарий этого моста) это НЕПРАВИЛЬНОЕ значение - VESC
 *          Tool считает устройство обычной веской и пытается прочитать
 *          MCCONF/APPCONF МОТОРА у самого моста (а не у вески за ним), мост
 *          на это не отвечает, конфигурация мотора в UI пустая/ошибка. Для
 *          нового кода указывайте VESC_BRIDGE_HW_TYPE_CUSTOM_MODULE (именно
 *          так представляется настоящий VESC Express).
 */
typedef enum
{
    VESC_BRIDGE_HW_TYPE_VESC          = 0, /* обычная веска - см. @warning выше, для хаба НЕ подходит */
    VESC_BRIDGE_HW_TYPE_VESC_BMS      = 1,
    VESC_BRIDGE_HW_TYPE_CUSTOM_MODULE = 2, /* значение настоящего VESC Express - рекомендуется для хаба */
} VESC_Bridge_HwType_t;

/**
 * @brief  Конфигурация для создания моста - см. VESC_Bridge_Init().
 */
typedef struct
{
    /** Шина (can_manager), на которой сидят вески, доступ к которым нужно
     *  дать через мост - указатель, полученный из CANMGR_Init() (см.
     *  can_manager.h). В отличие от версии ДО миграции на can_manager, эта
     *  шина НЕ обязана иметь уже зарегистрированные через VESC_CAN_Init()
     *  вески - мост теперь независимый потребитель can_manager, ему для
     *  собственной работы достаточно, что периферия уже настроена и
     *  запущена самим CANMGR_Init() (было VESC_CAN_HandleTypeDef* hcan,
     *  требовавший хотя бы одной вески на шине - до миграции периферию
     *  настраивал именно motor_vesc.c). */
    CANMGR_Handle_t *bus;

    /** "Личный" CAN ID моста на этой шине (0..255) - НЕ CAN ID какой-либо
     *  реальной вески. Нужен, чтобы veska-цель знала, куда по CAN отправить
     *  ответ на форвардированную команду (см. BRIDGE_PROTOCOL.md §3).
     *  ОБЯЗАННОСТЬ ВЫЗЫВАЮЩЕГО КОДА - убедиться, что это значение НЕ
     *  совпадает ни с одной веской (зарегистрированной через VESC_CAN_Init
     *  ИЛИ вообще присутствующей физически на шине - например, штатный
     *  VESC Express, если он тоже на этой шине) и ни с одним ДРУГИМ мостом
     *  на этой же шине - модуль это не проверяет и не может проверить. */
    uint8_t own_can_id;

    /** Колбэк отправки байт клиенту - см. VESC_Bridge_TxCallback_t.
     *  Обязателен (NULL здесь -> VESC_Bridge_Init() вернёт NULL). */
    VESC_Bridge_TxCallback_t tx_callback;

    /** Major/minor версия для локального ответа на COMM_FW_VERSION (см.
     *  BRIDGE_PROTOCOL.md §5) - VESC Tool спрашивает это при подключении к
     *  ЛЮБОМУ устройству, включая сам мост (не вески за ним - их
     *  COMM_FW_VERSION форвардится как обычная команда и отвечает реальная
     *  прошивка вески). Если не уверены, что указать - начните со значений,
     *  под которые заточена ваша версия VESC Tool. */
    uint8_t fw_version_major;
    uint8_t fw_version_minor;

    /** Короткое ASCII-имя "железа" для того же ответа на COMM_FW_VERSION -
     *  NULL-терминированная строка, статическая (лежит в вашей памяти,
     *  указатель хранится в мосте до его пересоздания, НЕ копируется).
     *  NULL -> будет использовано "STM32-BRIDGE" по умолчанию. Длиннее 31
     *  символа - обрезается (см. vesc_bridge.c). */
    const char *hw_name;

    /** "Тип железа" - см. VESC_Bridge_HwType_t за подробным @warning про
     *  значение по умолчанию. Для хаба без своего мотора указывайте
     *  VESC_BRIDGE_HW_TYPE_CUSTOM_MODULE. */
    VESC_Bridge_HwType_t hw_type;

    /** Число пользовательских конфигураций (custom_config_num в ответе на
     *  COMM_FW_VERSION) - для простого хаба без своих кастомных конфигов
     *  оставьте 0. */
    uint8_t custom_config_num;

    /** Указатель на 12 байт UUID для ответа на COMM_FW_VERSION, либо NULL -
     *  тогда будут отправлены 12 нулевых байт (как и раньше, до версии 1.9).
     *  НЕ копируется (как и hw_name/fw_name) - должен указывать на память,
     *  живущую как минимум до следующего VESC_Bridge_Init() с этим же br.
     *  Библиотека сама НЕ читает уникальный идентификатор МК (HAL_GetUIDwX
     *  специфичен для конкретной серии STM32/другого МК - остаётся на
     *  стороне вызывающего кода ради переносимости библиотеки, см. шапку
     *  motor_vesc.h про тот же принцип). VESC Tool использует UUID как
     *  идентификатор устройства - ненулевой и уникальный на шине настоятельно
     *  рекомендуется, если у вас несколько мостов/устройств одновременно. */
    const uint8_t *uuid12;

    /** NULL-терминированная строка "имени прошивки" (FW_NAME) для того же
     *  ответа - NULL/пустая строка сохраняет поведение до версии 1.9 (пустая
     *  строка). Длиннее 31 символа - обрезается (см. vesc_bridge.c). Не
     *  копируется, как и hw_name. */
    const char *fw_name;

    /** [v1.14] Сколько ждать (мс) новых байт при разборе НЕЗАВЕРШЁННОГО внешнего
     *  кадра (получили старт-байт и часть данных, а дальше тишина), прежде чем
     *  сбросить парсер. 0 = таймаут ВЫКЛЮЧЕН.
     *
     *  @warning Для надёжного упорядоченного транспорта-ПОТОКА (TCP, USB CDC)
     *           таймаут ВРЕДЕН: пауза там не означает потерю байта (TCP сам
     *           ретранслирует потерянный сегмент, например Windows через ~300
     *           мс), а сброс парсера посреди пакета превращает остаток пакета в
     *           "мусор", в котором может найтись байт 0x02/0x03 - и СЛЕДУЮЩИЙ
     *           нормальный пакет проглатывается как хвост ложного кадра
     *           (подтверждено фаззингом на реальном железе, ~3-4% серий при
     *           фрагментированной отправке). Для TCP/USB CDC рекомендуется 2000 мс (0 допустим,
     *           но ложный средний старт 0x03 тогда может съесть до ~1 КБ реальных пакетов), а границу сессий обозначайте VESC_Bridge_ResetRx().
     *           Для UART (возможна потеря/вставка байт) - порядка 300 мс.
     *
     *  @warning При обнулённой (memset 0) конфигурации таймаут ВЫКЛЮЧЕН - до
     *           версии 1.14 действовало неявное значение 300 мс. */
    uint32_t rx_timeout_ms;
} VESC_Bridge_Config_t;

/* ------------------------------------------------------------------------ */
/*  Создание моста                                                          */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Создаёт мост по заполненной конфигурации. Регистрирует в
 *         can_manager 5 точных (exact-match) фильтров приёма - по одному на
 *         cmd_id 5 (`CAN_PACKET_FILL_RX_BUFFER`), 6 (`_LONG`), 7
 *         (`PROCESS_RX_BUFFER`), 8 (`PROCESS_SHORT_BUFFER`), 18
 *         (`CAN_PACKET_PONG` - см. активный скан шины у COMM_PING_CAN,
 *         VESC_Bridge_Tick), каждый на (cmd_id<<8)|own_can_id - см.
 *         обоснование в BRIDGE_PROTOCOL.md.
 *
 * @param  config  заполненная конфигурация (см. VESC_Bridge_Config_t)
 * @retval указатель на VESC_Bridge_t (хранить у себя, использовать во всех
 *         остальных вызовах), либо NULL при ошибке: config == NULL,
 *         config->bus == NULL, tx_callback == NULL, исчерпан
 *         VESC_BRIDGE_MAX_INSTANCES, либо can_manager отклонил регистрацию
 *         хотя бы одного из 5 фильтров (реальное пересечение - например
 *         own_can_id уже занят другим мостом с тем же ID на этой шине,
 *         либо исчерпаны лимиты фильтров/групп масок can_manager).
 *
 * @warning Как и у VESC_CAN_Init() в motor_vesc.h - при частичном успехе
 *          регистрации (часть из 5 фильтров встала, следующий отклонён)
 *          уже зарегистрированные в can_manager фильтры НЕ отменяются (у
 *          can_manager в этой версии нет функции отмены регистрации) -
 *          функция всё равно возвращает NULL. Повторный VESC_Bridge_Init()
 *          с тем же own_can_id после устранения причины отказа будет
 *          пытаться зарегистрировать все 5 фильтров заново и получит отказ
 *          на уже зарегистрированных ранее (сам с собой).
 */
VESC_Bridge_t *VESC_Bridge_Init(const VESC_Bridge_Config_t *config);

/* ------------------------------------------------------------------------ */
/*  Приём байт от клиента (VESC Tool) - транспорт-независимая точка входа   */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Скармливает мосту очередную порцию байт, пришедших ОТКУДА УГОДНО -
 *         из обработчика приёма TCP-сокета (lwIP), из UART RX прерывания/
 *         DMA-колбэка, из USB CDC receive-колбэка (Virtual COM Port) и т.п.
 *         Можно вызывать хоть по одному байту, хоть большими кусками - парсер
 *         внутри побайтовый и не требует, чтобы кадр пришёл целиком за один
 *         вызов. Разбирает внешнее кадрирование протокола VESC Tool (см.
 *         BRIDGE_PROTOCOL.md §2); по накоплении полного и валидного (CRC
 *         совпал) пакета - либо отвечает локально (см. §5 там же), либо
 *         форвардит вложенную команду на CAN (см. §3-4 там же).
 *
 * @note   Может вызываться и из прерывания, и из основного цикла/задачи -
 *         сама по себе безопасна для любого контекста (см. также
 *         VESC_Bridge_OnCanFrame - если оба вызываются из РАЗНЫХ источников
 *         прерываний одновременно для ОДНОГО И ТОГО ЖЕ моста, внутреннее
 *         состояние моста защищено критическими секциями - как и остальной
 *         код этой библиотеки). Если ваш транспорт сам уже буферизует и
 *         отдаёт данные из основного цикла (типично для lwIP/сокетов) -
 *         вызывайте оттуда, дополнительная буферизация не нужна.
 *
 * @param  br    мост, полученный из VESC_Bridge_Init()
 * @param  data  входящие байты
 * @param  len   их количество
 */
void VESC_Bridge_FeedBytes(VESC_Bridge_t *br, const uint8_t *data, uint16_t len);

/**
 * @brief  [v1.14] Сбрасывает парсер входящего потока (отбрасывает недочитанный
 *         пакет и накопленные для ресинхронизации байты). Код транспорта ОБЯЗАН
 *         вызывать её при каждом НОВОМ подключении клиента и при обрыве
 *         соединения - иначе недочитанный пакет прошлой сессии "съест" начало
 *         первого пакета новой (особенно при rx_timeout_ms = 0). Не влияет на
 *         исходящий форвардинг и очередь.
 *
 *         Ресинхронизация (v1.14): при ошибке CRC/стоп-байта КОРОТКОГО кадра
 *         (<= 255 байт) уже принятые байты перепрогоняются через парсер в
 *         поисках настоящего старт-байта, а не отбрасываются целиком - потерянная
 *         граница пакета больше не "съедает" следующий нормальный пакет.
 * @param  br  мост
 */
void VESC_Bridge_ResetRx(VESC_Bridge_t *br);

/**
 * @brief  Периодическое обслуживание таймаутов - см. VESC_BRIDGE_FORWARD_TIMEOUT_MS
 *         и VESC_Bridge_Config_t.rx_timeout_ms. Вызывайте регулярно (например из
 *         того же цикла/таймера, откуда и VESC_CAN_SimulateTick, если она у
 *         вас используется) - раз в несколько десятков мс более чем
 *         достаточно, точная частота не критична.
 * @param  br  мост
 */
void VESC_Bridge_Tick(VESC_Bridge_t *br);

/* ------------------------------------------------------------------------ */
/*  Приём ответных кадров от весок по CAN                                   */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Обрабатывает один ответный CAN-кадр вески-цели.
 *
 * @note   [После миграции на can_manager] Вызывается АВТОМАТИЧЕСКИ - через
 *         callback, зарегистрированный VESC_Bridge_Init() в can_manager для
 *         5 точных фильтров моста (см. там же) - вызывать эту функцию из
 *         своего кода вручную больше не нужно (раньше требовалось звать её
 *         из своей реализации VESC_CAN_OnForeignFrame(), см. motor_vesc.h -
 *         эта функция и весь механизм "чужих кадров" удалены). Остаётся
 *         частью публичного API - на случай ручного разбора кадров или
 *         юнит-тестирования без реального can_manager.
 *
 * @warning Вызывается ИЗ ПРЕРЫВАНИЯ (изнутри диспетчеризации can_manager -
 *          `CANMGR_RxFifo_Handler`). При накоплении полного ответа МОЖЕТ
 *          вызвать ваш tx_callback (см. VESC_Bridge_TxCallback_t) прямо
 *          отсюда, из этого же контекста прерывания - учитывайте это в
 *          реализации tx_callback (см. предупреждение там же).
 *
 * @param  br      мост
 * @param  ext_id  29-битный Extended ID кадра как есть
 * @param  data    данные кадра
 * @param  len     длина данных, байт (0..8)
 */
void VESC_Bridge_OnCanFrame(VESC_Bridge_t *br, uint32_t ext_id, const uint8_t *data, uint8_t len);

/* ------------------------------------------------------------------------ */
/*  Взаимодействие со штатной отправкой команд (motor_vesc.h)               */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Правда ли, что прямо сейчас идёт форвардинг команды VESC Tool
 *         КОНКРЕТНОЙ веске (ждём от неё ответа) - на время активной
 *         настройки конкретной вески через VESC Tool стоит приостанавливать
 *         штатную отправку команд именно этой веске. Мост это не делает сам
 *         (никакой магии/скрытого вмешательства в VESC_CAN_SendXxx) -
 *         вызывайте эту функцию из своего управляющего цикла и сами
 *         решайте, пропустить ли на этот раз обычную команду для данной
 *         вески.
 *
 * @param  br       мост
 * @param  vesc_id  CAN ID вески, про которую спрашиваем
 * @retval 1 - да, идёт форвардинг именно этой веске (или начался недавно и
 *         ещё не протух по VESC_BRIDGE_FORWARD_TIMEOUT_MS); 0 - нет, либо
 *         br == NULL
 */
uint8_t VESC_Bridge_IsTargetActive(VESC_Bridge_t *br, uint8_t vesc_id);

/* ------------------------------------------------------------------------ */
/*  Точка расширения: нераспознанные локальные команды                      */
/* ------------------------------------------------------------------------ */

/**
 * @brief  Вызывается, когда мост принял от VESC Tool полный валидный внешний
 *         пакет, но его COMM_PACKET_ID - НЕ COMM_FORWARD_CAN и не одна из
 *         команд, которые мост умеет отвечать сам (COMM_FW_VERSION,
 *         COMM_PING_CAN - см. BRIDGE_PROTOCOL.md §5). Слабая функция —
 *         переопределите её в своём коде, чтобы добавить ответы на другие
 *         локальные команды (например COMM_ALIVE, если вашей версии VESC
 *         Tool важен ответ на неё - по имеющимся данным обычно не важен, см.
 *         BRIDGE_PROTOCOL.md). Чтобы ответить - соберите свой payload и
 *         передайте в VESC_Bridge_SendLocalReply().
 *
 * @param  br       мост
 * @param  payload  весь payload принятого пакета (включая сам COMM_PACKET_ID
 *                   первым байтом)
 * @param  len      его длина, байт
 */
void VESC_Bridge_OnLocalCommand(VESC_Bridge_t *br, const uint8_t *payload, uint16_t len);

/**
 * @brief  Заворачивает payload во внешнее кадрирование (см. BRIDGE_PROTOCOL.md
 *         §2) и отправляет через tx_callback - для использования из
 *         VESC_Bridge_OnLocalCommand() при реализации собственных локальных
 *         команд.
 * @param  br       мост
 * @param  payload  тело ответа (обычно начинается с того же COMM_PACKET_ID,
 *                   на который отвечаем)
 * @param  len      его длина, байт (не больше VESC_BRIDGE_MAX_PAYLOAD)
 */
void VESC_Bridge_SendLocalReply(VESC_Bridge_t *br, const uint8_t *payload, uint16_t len);

